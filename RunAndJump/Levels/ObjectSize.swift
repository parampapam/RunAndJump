import CoreGraphics

/// Размеры объектов, габариты которых всегда одинаковы. Единый источник —
/// и для размера узла, и для вычисления центра из нижнего-левого угла. В тайлах.
enum ObjectSize {
    static let player = TileSize.one
    /// Хитбокс уже спрайта, и это не поблажка, а физика края: тело держится на
    /// опоре, пока хоть краем перекрывает её, поэтому тело во весь тайл «висело»
    /// над пустотой, пока спрайт вышел за край почти целиком, и перешагивало
    /// проём в один тайл. Уже тайла — обязательно: ровно тайл проём не провалил бы.
    /// Ниже спрайта на запас: проход ровно в один тайл (под парящим блоком)
    /// с телом во всю высоту цеплялся макушкой за нижний угол блока и не
    /// пускал дальше. Тело стоит на тех же «ногах», что и спрайт, — запас
    /// снимается сверху.
    static let playerHitbox = TileSize(width: 0.5, height: 0.9)
    static let enemy  = TileSize(width: 0.75, height: 0.75)
    /// Спрайты наград (атлас Pickups) рисуют объект в центральной половине
    /// кадра, остальное — прозрачные поля. Узел — целый тайл, чтобы видимая
    /// часть была ~полтайла; хитбокс — по видимой части, а не по полям.
    static let pickup = TileSize.one
    static let pickupHitbox = TileSize(width: 0.5, height: 0.5)
    static let portal = TileSize(width: 0.75, height: 1.5)
    /// Флаг точки восстановления: древко занимает всю высоту кадра, полотнище —
    /// правую часть, поэтому объект ровно в тайл. Зона срабатывания — весь тайл:
    /// «пройти мимо флага» не должно требовать точного попадания в древко.
    static let checkpoint = TileSize.one
    static let ladder = TileSize(width: 0.85, height: 1)
    /// Снаряд снайпера. Спрайт, как и награды, нарисован в центре кадра с
    /// прозрачными полями: узел в полтайла даёт шарик примерно в четверть тайла.
    static let projectile = TileSize(width: 0.5, height: 0.5)
    /// Радиус хитбокса снаряда, тайлы — по видимому шарику, а не по полям кадра.
    static let projectileHitboxRadius: CGFloat = 0.14
}
