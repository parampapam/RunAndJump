import SpriteKit

/// Цвета сцены, которые нужны сразу нескольким узлам. Единый источник: иначе
/// «небо» за озером и фон самой сцены разъедутся при первой же правке.
enum ScenePalette {

    /// Небо — фон игровой сцены. Им же залито дно озера: за жидкостью земли
    /// нет, чтобы сквозь полупрозрачную воду не просвечивал грунт с травой.
    static let sky = SKColor(red: 0.5, green: 0.7, blue: 0.95, alpha: 1.0)
}
