import CoreGraphics

/// Слои отрисовки сцены (порядок по оси Z). Чем меньше значение — тем дальше.
/// Игровые объекты (игрок, враги, платформы, награды, портал) используют
/// значение по умолчанию `0` и потому рисуются поверх земли и декораций.
enum ZPosition {
    /// Сплошная заливка фона — самый дальний слой. Видна везде, где полосы
    /// фона ничего не рисуют.
    static let background: CGFloat = -100
    /// Верхняя полоса фона (облака).
    static let backgroundSky: CGFloat = -95
    /// Нижняя полоса фона (горы, холмы, океан) — поверх облаков: у самой линии
    /// горизонта силуэт гор должен закрывать небо, а не наоборот.
    static let backgroundHorizon: CGFloat = -90
    /// Декорации заднего плана (цветы, кусты, деревья). Позади них — только фон.
    static let decorationBack: CGFloat = -20
    /// Травяное покрытие земли — поверх декораций, но под игровыми объектами.
    static let ground: CGFloat = -10
    /// Флаги точек восстановления — поверх травы, но **позади** игрока: мимо
    /// флага проходят, а не сквозь него, поэтому древко не должно закрывать
    /// персонажа.
    static let checkpoint: CGFloat = -5
    /// Декорации переднего плана (факел на стене, свисающие лианы) — **перед**
    /// игроком (`0`), но **под** жидкостью (`hazard`): факел на берегу озера не
    /// должен всплывать поверх лавы.
    static let decorationFront: CGFloat = 3
    /// Опасные зоны (озёра воды и лавы) — **поверх** игровых объектов: зашедший
    /// в озеро игрок утоплен по пояс, и жидкость должна закрывать его нижнюю
    /// половину. Иначе он выглядит идущим по воде, а не в воде.
    static let hazard: CGFloat = 5
}
