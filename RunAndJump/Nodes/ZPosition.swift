import CoreGraphics

/// Слои отрисовки сцены (порядок по оси Z). Чем меньше значение — тем дальше.
/// Игровые объекты (игрок, враги, платформы, награды, портал) используют
/// значение по умолчанию `0` и потому рисуются поверх земли и декораций.
enum ZPosition {
    /// Фон сцены — самый дальний слой (появится позже).
    static let background: CGFloat = -100
    /// Декорации заднего плана (цветы, кусты, деревья). Позади них — только фон.
    static let decoration: CGFloat = -20
    /// Травяное покрытие земли — поверх декораций, но под игровыми объектами.
    static let ground: CGFloat = -10
}
