import CoreGraphics

/// Семантические команды ввода, не зависящие от источника.
///
/// Один и тот же набор событий порождают и экранный джойстик (`InputController`),
/// и физический геймпад (`GamepadInput`). Сцена реагирует на смысл команды,
/// ничего не зная о том, откуда она пришла — это позволяет добавлять новые
/// источники ввода, не трогая игровую логику.
protocol GameInputDelegate: AnyObject {

    /// Аналоговое направление движения от источника ввода.
    ///
    /// Компоненты в диапазоне [-1, 1]: `horizontal` — влево/вправо,
    /// `vertical` — вниз/вверх (положительный = вверх). Модуль каждой оси
    /// задаёт долю максимальной скорости, поэтому слабое отклонение стика
    /// даёт медленное движение, сильное — быстрое.
    func inputDidUpdateDirection(horizontal: CGFloat, vertical: CGFloat)

    /// Нажата кнопка прыжка.
    func inputDidPressJump()
}
