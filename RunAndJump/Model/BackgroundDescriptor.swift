import CoreGraphics

/// Декларативное описание фона уровня: сплошная заливка, поверх которой лежат
/// две горизонтальные полосы — нижняя (горы, холмы, стена интерьера) и верхняя
/// (облака). Чистые данные, без SpriteKit; раскладку считает `BackgroundLayout`.
///
/// Заливка есть всегда и видна там, где полоса ничего не рисует
/// (`HorizonSegment.fill`, слой, которого у стиля нет) — отдельного «пустого»
/// фона не существует, пустота это и есть заливка.
///
/// Подземный уровень описывается теми же полями: линия горизонта поднимается до
/// потолка, нижняя полоса выкладывается `.interior` и кроет экран целиком, а
/// верхняя получает **пустой список** сегментов.
struct BackgroundDescriptor: Equatable {
    let fill: BackgroundFill
    /// Нижняя полоса — от низа уровня до линии горизонта.
    let horizon: BackgroundStrip<HorizonSegment>
    /// Верхняя полоса — от линии горизонта вверх.
    let sky: BackgroundStrip<SkySegment>
    /// Линия стыка полос — в тайлах от низа **уровня**, а не экрана. Поэтому
    /// при подъёме игрока горизонт уходит вниз и открывается небо; будь она
    /// привязана к камере, линия была бы приколочена к глазу и не шевелилась.
    let horizonLineInTiles: CGFloat
}

/// Одна полоса фона: чем заполнена и насколько широк её сегмент.
///
/// Список сегментов **зациклен**: полоса шире списка повторяет чередование с
/// начала. Поэтому уровню достаточно перечислить один период узора, а не
/// замостить всю свою длину.
///
/// Обратное не работает: список **длиннее** полосы показывает только начало, а
/// хвост не увидят никогда. Сколько сегментов влезет — считается от ширины
/// экрана и потому зависит от устройства (на 16:9 в нижнюю полосу из тайлов по
/// 8 их помещается около четырёх). Поэтому узор держат коротким: он должен
/// успеть повториться, а не оборваться.
/// `Sendable` у параметра не для многопоточности, а чтобы описание уровня
/// осталось `Sendable`: без ограничения дженерик рвёт вывод, и `Levels`
/// перестаёт компилироваться под Swift 6.
struct BackgroundStrip<Segment: Equatable & Sendable>: Equatable, Sendable {
    let segments: [Segment]
    /// Ширина одного сегмента в тайлах. Высота полосы не задаётся: нижняя
    /// растянута до линии горизонта, верхняя — до верха видимой области
    /// (считает `BackgroundLayout`).
    ///
    /// У гряды ширина не обязана совпадать с пропорцией картинки: у холмов и
    /// гор левый и правый край — однотонная заливка, поэтому растягивается
    /// только она, а не силуэт.
    ///
    /// У `.interior` — обязана: стена кроет экран целиком, однотонных краёв у
    /// неё нет, и растянутый сегмент видно как сплющенную кладку.
    let widthInTiles: CGFloat
}

/// Сплошная подложка под обеими полосами. Приколочена к камере: не ездит и не
/// масштабируется, поэтому дырок в фоне не бывает при любом положении камеры.
enum BackgroundFill: Equatable {
    case solid
}

/// Сегмент нижней полосы.
///
/// Соседство любое: у `hills` и `mountains` небо нарисовано ровно тем же
/// цветом, что и заливка, поэтому прямоугольник сегмента невидим, а стык с
/// любым соседом не читается.
enum HorizonSegment: Equatable {
    case hills
    case mountains
    /// Сплошная стена интерьера — пещеры, замка, подземелья.
    ///
    /// Под землёй неба нет, поэтому уровень в таком стиле поднимает линию
    /// горизонта до потолка (`horizonLineInTiles` = высота уровня) и оставляет
    /// верхнюю полосу пустой: нижняя закрывает экран целиком в любом положении
    /// камеры. Отдельного вида полосы для этого не нужно — «интерьер» это тот
    /// же сегмент горизонта, просто горизонт у него над головой.
    ///
    /// Картинка обязана тайлиться по горизонтали: в отличие от гряды, у неё
    /// нет однотонных краёв, и стык соседних сегментов виден.
    case interior
    /// Ничего не рисуем — видно заливку. Разрыв в гряде.
    case fill

    /// Сегмент, который ничего не рисует **по замыслу**, а не потому, что у
    /// стиля не нашлось картинки. Разница нужна валидации: пустота на месте
    /// `fill` — это узор, пустота на месте `hills` — забытый слой в каталоге.
    var isBlank: Bool {
        switch self {
        case .fill: return true
        case .hills, .mountains, .interior: return false
        }
    }
}

/// Сегмент верхней полосы.
///
/// Пустого случая здесь **нет**, и это следствие арта: у облаков верх неба
/// темнее заливки, поэтому пустой сегмент рядом с облачным дал бы вертикальную
/// границу цвета через весь верх экрана. Уровень без облаков задаёт пустой
/// список сегментов, а не чередует их с пустотой.
enum SkySegment: Equatable {
    case clouds
}

/// Скорости параллакса — доля хода камеры, на которую смещается полоса.
/// `0` — полоса приколочена к камере (не двигается относительно экрана),
/// `1` — полоса стоит в мире неподвижно, как обычный объект уровня.
///
/// Это константы, а не поля описания уровня, намеренно: иначе каждый уровень
/// смог бы завести себе свою физику фона, и одинаковые на вид горы ездили бы
/// с разной скоростью.
enum BackgroundParallax {
    /// Нижняя полоса ближе, поэтому едет заметнее верхней.
    static let horizon: CGFloat = 0.35
    static let sky: CGFloat = 0.15
    /// По вертикали **обе** полосы едут одинаково. Разные скорости развели бы
    /// верх нижней полосы и низ верхней, и при подъёме игрока между ними
    /// открылась бы щель с заливкой: линия горизонта одна и не может ехать с
    /// двумя скоростями сразу.
    static let vertical: CGFloat = 0.2
}
