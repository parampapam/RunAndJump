import Foundation

/// Идентификатор декорации — открытый, по образцу `Notification.Name`.
///
/// Раньше это был `enum DecorationKind`, и за ним не стояло ничего, кроме
/// раскладки плиток: ни сцена, ни правила игры на вид декорации не смотрели.
/// Закрытый тип в такой роли ничего не защищает — он только запрещает стилю
/// иметь свой набор украшений, потому что список видов пришлось бы держать
/// общим на все стили сразу.
///
/// Правило разделения: если код на этом **ветвится** — закрытый `enum`; если от
/// этого зависит **только картинка** — открытый идентификатор.
///
/// Идентификаторы **локальны стилю**: `"torch"` в подземелье и в замке — разные
/// записи в разных каталогах, а не одна общая декорация. Ни алиасов, ни
/// глобального реестра здесь нет и не должно быть.
///
/// Цена открытости — компилятор больше не ловит опечатки. Замена ему —
/// `LevelValidation`, которая сверяет уровень с каталогом его стиля.
struct DecorationID: RawRepresentable, Hashable, Sendable {

    let rawValue: String

    init(_ rawValue: String) {
        self.rawValue = rawValue
    }

    init(rawValue: String) {
        self.rawValue = rawValue
    }
}
