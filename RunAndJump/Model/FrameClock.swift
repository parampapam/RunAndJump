import Foundation

/// Переводит абсолютное время кадра в дельту `dt` между соседними кадрами.
///
/// Игровой цикл SpriteKit отдаёт абсолютную метку времени, а движению нужна
/// разница с прошлым кадром. Эта чистая мелочь раньше дублировалась в каждом
/// узле, который ведёт что-то по времени (`MovingPlatform`, `PatrollingMovement`).
///
/// Первый кадр только фиксирует точку отсчёта и возвращает `nil` —
/// корректный `dt` появляется со второго вызова.
///
/// Дельта ограничена сверху (`maximumDelta`). Часы кадров продолжают идти,
/// пока приложение свёрнуто, а рендер стоит, — поэтому первый кадр после
/// разворачивания даёт разницу в десятки секунд. Без потолка всё, что ведётся
/// по времени (патрулирование врагов, движущиеся платформы, езда игрока на
/// платформе), сделало бы один гигантский шаг: враги телепортируются, платформа
/// улетает за пределы своего диапазона. Тот же скачок даёт любая просадка —
/// подгрузка атласа, точка останова в отладчике.
///
/// Цена потолка: если кадры идут реже, чем `maximumDelta`, мир замедляется
/// вместо того, чтобы дёргаться. Для платформера это правильный размен —
/// пропущенное время лучше потерять, чем проскочить сквозь стену.
struct FrameClock {

    /// 1/30 секунды. Ниже 30 кадров игра идёт в замедленном темпе, но остаётся
    /// управляемой и предсказуемой.
    static let defaultMaximumDelta: TimeInterval = 1.0 / 30.0

    private let maximumDelta: TimeInterval
    private var lastUpdateTime: TimeInterval?

    init(maximumDelta: TimeInterval = FrameClock.defaultMaximumDelta) {
        self.maximumDelta = maximumDelta
    }

    /// Секунды, прошедшие с прошлого вызова (не больше `maximumDelta`),
    /// либо `nil` на самом первом кадре.
    mutating func tick(at time: TimeInterval) -> TimeInterval? {
        defer { lastUpdateTime = time }
        guard let last = lastUpdateTime else { return nil }
        // Отрицательная дельта означала бы, что часы пошли назад: не доверяем ей.
        return min(max(0, time - last), maximumDelta)
    }
}
